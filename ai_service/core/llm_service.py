def get_llm_service(provider_name: Optional[str] = None) -> BaseLLMProvider:
    """Factory to retrieve configured LLM service provider."""
    provider = (provider_name or settings.LLM_PROVIDER).lower()
    if provider == "gemini":
        return GeminiProvider()
    elif provider == "mock":
        return MockLLMProvider()
    else:
        return GeminiProvider()
