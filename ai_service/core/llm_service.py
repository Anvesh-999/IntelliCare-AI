            ref_text = ref_match.group(1).strip() if ref_match else ""
            lines = [l.strip() for l in ref_text.split("\n") if l.strip() and not l.strip().startswith("[") and not l.strip().startswith("Source")][:3]
            grounded_snippet = " ".join(lines) if lines else "Verified reference guidelines provide evidence regarding this inquiry."
