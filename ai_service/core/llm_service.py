T = TypeVar("T", bound=BaseModel)

class LLMBaseException(Exception):
    """Base exception for LLM service errors."""
    pass

class LLMAuthenticationError(LLMBaseException):
    """Raised when provider credentials are missing or rejected."""
    pass

class LLMTimeoutError(LLMBaseException):
    """Raised when provider call exceeds the configured timeout."""
    pass

class LLMRateLimitError(LLMBaseException):
    """Raised when provider rate limits / 429 occurs."""
    pass

class LLMSchemaValidationError(LLMBaseException):
    """Raised when LLM structured output fails schema validation."""
    pass

class LLMProviderError(LLMBaseException):
    """Generic error from LLM provider."""
    pass


def extract_and_validate_json(raw_text: str, schema_class: Type[T]) -> T:
    """
    Cleans, parses, and validates JSON against a target Pydantic schema model.
    Handles code fences, whitespace, and schema validation errors safely.
    """
    cleaned = raw_text.strip()
    
    # Strip markdown code fences if present
    match = re.search(r'```(?:json)?\s*([\s\S]*?)\s*```', cleaned)
    if match:
        cleaned = match.group(1).strip()
    else:
        # Match outermost curly braces
        braces_match = re.search(r'(\{[\s\S]*\})', cleaned)
        if braces_match:
            cleaned = braces_match.group(1).strip()

    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError as json_err:
        logger.error("Failed to parse JSON from LLM response: %s", sanitize_for_logs(str(json_err)))
        raise LLMSchemaValidationError(f"Invalid JSON generated by model: {str(json_err)}")

    try:
        return schema_class.model_validate(data)
    except ValidationError as val_err:
        logger.error("Pydantic schema validation failure: %s", sanitize_for_logs(str(val_err)))
        raise LLMSchemaValidationError(f"Schema validation failure: {str(val_err)}")


class BaseLLMProvider(ABC):
    """Abstract Base Class for LLM providers."""
    
    @abstractmethod
    async def generate_response(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        history: Optional[List[ChatMessage]] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None
    ) -> Dict[str, Any]:
        """Generate unstructured text response asynchronously."""
        pass

    @abstractmethod
    async def generate_structured_response(
        self,
        prompt: str,
        schema_class: Type[T],
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None
    ) -> T:
        """Generate guaranteed structured response adhering to Pydantic schema."""
        pass


class GeminiProvider(BaseLLMProvider):
    """
    Google Gemini provider using the official `google-genai` SDK.
    Supports asynchronous generation, model selection, timeouts, bounded retries,
    and constrained structured JSON generation.
    """

    def __init__(self, api_key: Optional[str] = None):
        if api_key is not None:
            self.api_key = api_key.strip() if api_key.strip() else None
        else:
            self.api_key = settings.effective_gemini_key
        self._client = None
        if self.api_key:
            try:
                from google import genai
                self._client = genai.Client(api_key=self.api_key)
                logger.info("Initialized Google GenAI client with key: %s", mask_secret(self.api_key))
            except Exception as e:
                logger.error("Failed to initialize Google GenAI Client: %s", sanitize_for_logs(str(e)))
        else:
            logger.warning("No Gemini API key detected. GeminiProvider will fail if invoked directly.")

    async def generate_response(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        history: Optional[List[ChatMessage]] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None
    ) -> Dict[str, Any]:
        if not self.api_key or not self._client:
            raise LLMAuthenticationError("GEMINI_API_KEY is not configured or is invalid. Please set GEMINI_API_KEY in ai_service/.env.")

        chosen_model = model or settings.GEMINI_MODEL
        sys_instruct = system_instruction or build_system_instruction()
        temp = temperature if temperature is not None else settings.LLM_TEMPERATURE

        contents = []
        if history:
            for turn in history:
                role = "user" if turn.role in ["user", "patient"] else "model"
                contents.append({"role": role, "parts": [{"text": turn.content}]})
        contents.append({"role": "user", "parts": [{"text": prompt}]})

        config_dict = {
            "system_instruction": sys_instruct,
            "temperature": temp,
            "max_output_tokens": settings.LLM_MAX_OUTPUT_TOKENS,
        }

        max_retries = settings.LLM_MAX_RETRIES
        timeout_seconds = settings.LLM_TIMEOUT_SECONDS

        for attempt in range(1, max_retries + 1):
            try:
                logger.info("Calling Gemini API (model=%s, attempt=%d/%d)...", chosen_model, attempt, max_retries)
                
                async def _call_api():
                    return await self._client.aio.models.generate_content(
                        model=chosen_model,
                        contents=contents,
                        config=config_dict
                    )

                response = await asyncio.wait_for(_call_api(), timeout=timeout_seconds)

                if not response or not response.text:
                    raise LLMProviderError("Empty response returned from Gemini API.")

                return {
                    "text": response.text.strip(),
                    "model": chosen_model,
                    "provider": "gemini",
                    "attempts": attempt
                }

            except asyncio.TimeoutError:
                logger.warning("Gemini API call timed out after %.1f seconds on attempt %d", timeout_seconds, attempt)
                if attempt == max_retries:
                    raise LLMTimeoutError(f"Gemini API request timed out after {timeout_seconds} seconds.")
                await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS * (2 ** (attempt - 1)))

            except Exception as e:
                err_msg = sanitize_for_logs(str(e))
                logger.error("Gemini API error on attempt %d: %s", attempt, err_msg)
                
                if "503" in err_msg or "UNAVAILABLE" in err_msg or "high demand" in err_msg:
                    if chosen_model != settings.GEMINI_FALLBACK_MODEL:
                        logger.warning("Gemini model %s unavailable (503). Switching to fallback model %s.", chosen_model, settings.GEMINI_FALLBACK_MODEL)
                        chosen_model = settings.GEMINI_FALLBACK_MODEL
                        await asyncio.sleep(0.5)
                        continue

                if "429" in err_msg or "RESOURCE_EXHAUSTED" in err_msg:
                    if attempt == max_retries:
                        raise LLMRateLimitError(f"Gemini API rate limit exceeded: {err_msg}")
                    await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS * (2 ** attempt))
                    continue

                if "400" in err_msg and "API_KEY" in err_msg or "403" in err_msg or "PERMISSION_DENIED" in err_msg:
                    raise LLMAuthenticationError(f"Gemini API authentication failed: {err_msg}")

                if attempt == max_retries:
                    raise LLMProviderError(f"Gemini generation failed: {err_msg}")

                await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS * (2 ** (attempt - 1)))

    async def generate_structured_response(
        self,
        prompt: str,
        schema_class: Type[T],
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: Optional[float] = None
    ) -> T:
        if not self.api_key or not self._client:
            raise LLMAuthenticationError("GEMINI_API_KEY is not configured or is invalid. Please set GEMINI_API_KEY in ai_service/.env.")

        chosen_model = model or settings.GEMINI_MODEL
        sys_instruct = system_instruction or build_system_instruction()
        temp = temperature if temperature is not None else settings.LLM_TEMPERATURE

        # Instruct model explicitly for JSON output
        structured_prompt = (
            f"{prompt}\n\nIMPORTANT: Return ONLY a valid JSON object matching the requested schema. "
            f"Do not invent medical measurements or values that are not stated. "
            f"Clearly delineate facts from general explanations."
        )

        from google.genai import types
        config = types.GenerateContentConfig(
            system_instruction=sys_instruct,
            temperature=temp,
            max_output_tokens=settings.LLM_MAX_OUTPUT_TOKENS,
            response_mime_type="application/json",
            response_schema=schema_class
        )

        max_retries = settings.LLM_MAX_RETRIES
        timeout_seconds = settings.LLM_TIMEOUT_SECONDS

        for attempt in range(1, max_retries + 1):
            try:
                logger.info("Calling Gemini Structured API (model=%s, schema=%s, attempt=%d/%d)...",
                            chosen_model, schema_class.__name__, attempt, max_retries)

                async def _call_api():
                    return await self._client.aio.models.generate_content(
                        model=chosen_model,
                        contents=structured_prompt,
                        config=config
                    )

                response = await asyncio.wait_for(_call_api(), timeout=timeout_seconds)

                if not response or not response.text:
                    raise LLMProviderError("Empty response returned from Gemini structured endpoint.")

                return extract_and_validate_json(response.text, schema_class)

            except LLMSchemaValidationError as val_err:
                logger.warning("Structured output validation error on attempt %d: %s", attempt, str(val_err))
                if attempt == max_retries:
                    raise
                await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS)

            except asyncio.TimeoutError:
                if attempt == max_retries:
                    raise LLMTimeoutError(f"Gemini structured request timed out after {timeout_seconds}s.")
                await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS * (2 ** (attempt - 1)))

            except Exception as e:
                err_msg = sanitize_for_logs(str(e))
                logger.error("Gemini structured call error on attempt %d: %s", attempt, err_msg)
                if "503" in err_msg or "UNAVAILABLE" in err_msg or "high demand" in err_msg:
                    if chosen_model != settings.GEMINI_FALLBACK_MODEL:
                        logger.warning("Gemini model %s unavailable (503). Switching to fallback model %s.", chosen_model, settings.GEMINI_FALLBACK_MODEL)
                        chosen_model = settings.GEMINI_FALLBACK_MODEL
                        await asyncio.sleep(0.5)
                        continue

                if "429" in err_msg or "RESOURCE_EXHAUSTED" in err_msg:
                    if attempt == max_retries:
                        raise LLMRateLimitError(f"Gemini API rate limit exceeded: {err_msg}")
                    await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS * (2 ** attempt))
                    continue
                if "400" in err_msg and "API_KEY" in err_msg or "403" in err_msg or "PERMISSION_DENIED" in err_msg:
                    raise LLMAuthenticationError(f"Gemini API authentication failed: {err_msg}")
                if attempt == max_retries:
                    raise LLMProviderError(f"Gemini structured generation failed: {err_msg}")
                await asyncio.sleep(settings.LLM_RETRY_DELAY_SECONDS * (2 ** (attempt - 1)))


